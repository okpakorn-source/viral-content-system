export const BLACKLIST_PATTERNS = Object.freeze([
  // กฎหมายร้ายแรง
  'คลิปหลุด', 'คลิปหน้าคล้าย', 'ข่มขืน', 'ฆ่า', 'ฆาตกรรม',
  'ยาเสพติด', 'ยาบ้า', 'ยาไอซ์', 'กัญชา',
  // สถาบัน
  'ม.112', 'หมิ่นสถาบัน', 'ลบหลู่', 'หมิ่นพระบรม',
  // ส่วนตัวร้ายแรง
  'ชู้', 'มือที่สาม', 'นอกใจ', 'เปลือย', 'โป๊',
  'ท้องก่อนแต่ง', 'โรคติดต่อ', 'เอดส์', 'HIV',
  // FB Policy
  'ยั่วยุ', 'เหยียดเชื้อชาติ', 'ฆ่าตัวตาย', 'ทำร้ายตัวเอง',
  // อาชญากรรม
  'แก๊งคอลเซ็นเตอร์', 'ฟอกเงิน', 'พนันออนไลน์',
]);

/**
 * คำประสมปลอดภัยของคำต้องห้ามบางคำ: ลบคำประสมที่ยกเว้นออกก่อนเทียบ "เฉพาะคำต้องห้ามคำนั้น"
 *   — 'ฆ่า' ตัวอื่นในข้อความเดียวกันยังจับได้ ('ฆ่าเชื้อแล้วฆ่าคน' = จับ) · คำต้องห้ามอื่น (เช่น 'ฆ่าตัวตาย') ไม่ถูกกระทบ
 * ตั้งใจให้น้อยที่สุด: ไม่ยกเว้น ยาฆ่าแมลง/ยาฆ่าหญ้า (ข่าวไทยมักมากับการทำร้ายตัวเอง) — เพิ่มคำต้องมีเหตุ + เทส
 * (regex ต้องมีธง g — ห้าม freeze ตัว regex เพราะ replace ตั้ง lastIndex)
 */
export const BLACKLIST_EXCEPTIONS = Object.freeze({
  'ฆ่า': Object.freeze([/ฆ่าเชื้อ(?!ชาติ)/gu]), // ฆ่าเชื้อ(โรค)/ยาฆ่าเชื้อ = สุขอนามัย · 'ฆ่า'+'เชื้อชาติ' ไม่นับเป็นข้อยกเว้น
});

const LOWER = BLACKLIST_PATTERNS.map((w) => w.toLowerCase());
const EXCEPTIONS_AT = BLACKLIST_PATTERNS.map((w) => BLACKLIST_EXCEPTIONS[w] || null);

/** คืนรายการคำต้องห้ามที่พบในข้อความ (ไม่ซ้ำ ตามลำดับรายการ) */
export function findBlacklist(text) {
  if (text == null) return [];
  const lower = String(text).toLowerCase();
  if (!lower) return [];
  const hits = [];
  for (let i = 0; i < LOWER.length; i++) {
    const ex = EXCEPTIONS_AT[i];
    const hay = ex ? ex.reduce((s, re) => s.replace(re, ' '), lower) : lower;
    if (hay.includes(LOWER[i])) hits.push(BLACKLIST_PATTERNS[i]);
  }
  return hits;
}

/** true เมื่อมีคำต้องห้ามอย่างน้อย 1 คำ */
export function containsBlacklist(text) {
  return findBlacklist(text).length > 0;
}
