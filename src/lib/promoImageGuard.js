// วลีเฉพาะที่บ่งว่า "ภาพนี้คือกราฟิก" (ไม่ใช่แค่พูดถึงคำว่ากราฟิกลอยๆ)
const _GRAPHIC_PHRASE_RE = /กราฟิกล้วน|แถบกราฟิก|การ์ดกราฟิก|คอลลาจกราฟิก|กราฟิกทับ|ข้อความกราฟิก/;
// วลีเฉพาะที่บ่งว่า "ภาพนี้คือโปสเตอร์" (ไม่ใช่แค่ "คนยืนอยู่กับโปสเตอร์" ในภาพข่าวจริง)
const _POSTER_PHRASE_RE = /โปสเตอร์ล้วน|เป็นโปสเตอร์|ภาพโปสเตอร์|ปกโปสเตอร์|การ์ดโปสเตอร์/;

// รายการ pattern ที่ "เจอที่ไหนในข้อความก็แบน" (ไม่ต้องมีคำอื่นประกอบ) — คัดมาเฉพาะคำที่จำเพาะพอแล้ว (ความเสี่ยงชนคำอื่นต่ำ)
const POSITIVE_PATTERNS = [
  _POSTER_PHRASE_RE,
  /โปรโมท/,
  /ปกรายการ/,
  /ตัวหนังสือใหญ่/,
  _GRAPHIC_PHRASE_RE,
  /logo\s*รายการ/i,
];

const NEGATION_RE = /ไม่มี|ไม่ใช่|ปราศจาก/;
const NEGATION_LOOKBACK = 12; // ตัวอักษร — คำปฏิเสธต้องอยู่ "ก่อนหน้า" คำที่แมตช์ไม่เกินนี้ถึงนับว่าเป็นการปฏิเสธ

// คำปฏิเสธอยู่ในช่วงก่อนหน้าตำแหน่ง index หรือไม่ (ดูเฉพาะข้อความก่อนหน้า ไม่ดูข้อความหลัง — กันเคสปฏิเสธคนละประโยค/คนละประเด็น)
function _isNegatedBefore(text, index) {
  const start = Math.max(0, index - NEGATION_LOOKBACK);
  return NEGATION_RE.test(text.slice(start, index));
}

// ตรวจ 1 ข้อความ (triage.note) ว่าเข้าข่าย "ภาพโปรโมท/ฉากหลังรก" หรือไม่
export function isPromoNote(note) {
  const text = String(note || '');
  if (!text) return false;

  // (ค) "รายการ" + "ฉากหลัง" ต้องเจอทั้งคู่ ไม่ผูกลำดับ
  const idxRaykan = text.indexOf('รายการ');
  const idxBackdrop = text.indexOf('ฉากหลัง');
  if (idxRaykan !== -1 && idxBackdrop !== -1) {
    if (!_isNegatedBefore(text, idxRaykan) && !_isNegatedBefore(text, idxBackdrop)) return true;
  }

  // (ก)(ข) วลีเฉพาะอื่นๆ — เจอที่ไหนก็ได้ในข้อความ แต่ต้องไม่ถูกปฏิเสธนำหน้าใกล้ๆ
  for (const re of POSITIVE_PATTERNS) {
    const m = re.exec(text);
    if (m && !_isNegatedBefore(text, m.index)) return true;
  }
  return false;
}

// ตรวจ 1 แถวพูลรูป (ต้องมี triage.note) — ทางเข้าใช้จริงจาก caller (megaAdapters.js/compose-test route.js)
export function isPromoImage(x) {
  return isPromoNote(x?.triage?.note);
}

export default Object.freeze({ isPromoNote, isPromoImage });
