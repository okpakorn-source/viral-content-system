//   (ค) "รายการ" + "ฉากหลัง" ต้องเจอ "ทั้งคู่" ในข้อความ ไม่ผูกลำดับก่อน-หลัง (ประโยคไทยสลับที่ได้)
//   (ง) กันคำปฏิเสธ: ถ้ามี "ไม่มี/ไม่ใช่/ปราศจาก" อยู่ "ใกล้ๆ" (ก่อนหน้าไม่เกิน NEGATION_LOOKBACK ตัวอักษร)
//       คำที่แมตช์ → ไม่นับเป็นภาพโปรโมท (เช่น "ไม่มีกราฟิกทับ", "ไม่ใช่โปสเตอร์")
