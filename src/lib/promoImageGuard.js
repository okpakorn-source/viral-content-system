//       ต้องเป็นวลีเฉพาะที่บ่งว่า "ภาพนี้คือกราฟิก/ถูกกราฟิกทับ" เท่านั้น
//   (ข) คำ "โปสเตอร์" เดี่ยวๆ ก็กว้างเกิน (เคสจริง "ยืนถ่ายกับโปสเตอร์ในงานเปิดตัว" = ภาพข่าวจริงของคน
