/**
 * Recursively sanitize output — replace คำเสี่ยงในทุก string ภายใน object/array
 * @param {any} obj — parsed JSON response จาก AI
 * @returns {any} — sanitized version
 */
export function sanitizeOutput(obj) {
  // 🔴 ★ 25 ก.ค. 69 (เจ้าของสั่ง): ปิดระบบคำกรองทั้งหมด — "พนักงานเกลาเนื้อก่อนใส่เจนอยู่แล้ว กฎนี้ไม่จำเป็น"
  //    เหตุผล: การแทนคำอัตโนมัติทำเนื้อหาเพี้ยน/บิดข้อเท็จจริง (เช่น "ฆ่าเชื้อ" → "ทำให้เสียชีวิตเชื้อ")
  //    ตอนนี้ค่าปริยาย = ไม่กรองอะไรเลย ปล่อยเนื้อผ่านดิบ 100%
  //    เปิดคืนได้ทันทีถ้าเปลี่ยนใจ: ตั้ง env WORD_FILTER=on (ไม่ต้องแก้โค้ด)
  if (process.env.WORD_FILTER !== 'on') return obj;
  if (typeof obj === 'string') {
    let result = obj;
    for (const [pattern, replacement] of SAFETY_REPLACEMENTS) {
      result = result.replace(pattern, replacement);
    }
    return result;
  }
  if (Array.isArray(obj)) {
    return obj.map(item => sanitizeOutput(item));
  }
  if (obj && typeof obj === 'object') {
    const sanitized = {};
    for (const [key, val] of Object.entries(obj)) {
      sanitized[key] = sanitizeOutput(val);
    }
    return sanitized;
  }
  return obj;
}
