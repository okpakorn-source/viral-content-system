// mapCategory — map free-text category ไปยัง constrained enum
// ═══════════════════════════════════════════════════════════════
/**
 * @param {string} freeText - AI category from Stage 1 or free text
 * @returns {string} constrained Prompt Library category
 */
export function mapCategory(freeText) {
  if (!newCardCatsOn()) {
    // ── สวิตช์ปิด (ค่าเริ่มต้น): โค้ดเดิมทุกตัวอักษร — ผลเดิมไบต์ต่อไบต์ ──
    if (!freeText) return 'ดราม่าสังคม';
    const lower = freeText.toLowerCase().trim();

    // Exact match first
    if (CATEGORY_MAP[freeText]) return CATEGORY_MAP[freeText];
    if (CATEGORY_MAP[lower]) return CATEGORY_MAP[lower];

    // Partial match
    for (const [key, val] of Object.entries(CATEGORY_MAP)) {
      if (lower.includes(key) || key.includes(lower)) return val;
    }

    return 'ดราม่าสังคม'; // default
  }

  // ── สวิตช์ NEW_CARD_CATS_V1 เปิด: หมวดใหม่ 3 หมวด + ย้าย mapping (FINAL F9 บรรทัด 41) ──
  if (!freeText) return 'ดราม่าสังคม';
  const lower = freeText.toLowerCase().trim();

  // ป้ายผลการแข่งตรงตัว ('ชนะ'/'แพ้'/'เสมอ' — exact เท่านั้น กันดูดข้อความการเมือง/สุขภาพ)
  if (Object.prototype.hasOwnProperty.call(NEW_CATS_EXACT_ONLY, lower)) return NEW_CATS_EXACT_ONLY[lower];

  // Exact match first (ตารางรวม: คีย์เดิมหลังย้าย + คีย์หมวดใหม่)
  const map = effectiveCategoryMap();
  if (map[freeText]) return map[freeText];
  if (map[lower]) return map[lower];

  // ป้ายเดี่ยวสั้นที่ตั้งใจ ('ศาล'/'พระ'/'คดี') — exact เท่านั้น (ดูเหตุผลที่ NEW_CATS_BARE_LABELS)
  if (Object.prototype.hasOwnProperty.call(NEW_CATS_BARE_LABELS, lower)) return NEW_CATS_BARE_LABELS[lower];

  // Partial match ชั้นหมวดใหม่ก่อน (หมวดเฉพาะมาก่อน · คีย์ยาวก่อน) — เทียบบนข้อความที่ล้างคำปลอมแล้ว (NEW_CATS_FALSE_FRIENDS)
  // ทิศเดียว: ข้อความ ⊇ คีย์ เท่านั้น (ไม่มี key.includes(label) — เศษหลังล้างอย่าง 'ครู' หรือป้ายสั้น 'ทอง' จะไม่ชนคีย์ยาว)
  // ข้อความว่าง (หลังล้าง) ข้ามชั้นนี้ ให้ไหลไปชั้นเดิมเหมือนปิดสวิตช์
  const probe = lower.replace(NEW_CATS_FALSE_FRIENDS, '');
  if (probe) {
    for (const [key, val] of NEW_CATS_PARTIAL_ENTRIES) {
      if (probe.includes(key)) return val;
    }
  }

  // Partial match คีย์เดิม — ลำดับเดิมเป๊ะ เปลี่ยนเฉพาะปลายทางของป้ายที่ย้าย (FINAL F9 บรรทัด 41)
  for (const [key, val] of Object.entries(CATEGORY_MAP)) {
    if (lower.includes(key) || key.includes(lower)) {
      return Object.prototype.hasOwnProperty.call(NEW_CATS_MOVED, key) ? NEW_CATS_MOVED[key] : val;
    }
  }

  return 'ดราม่าสังคม'; // default
}


