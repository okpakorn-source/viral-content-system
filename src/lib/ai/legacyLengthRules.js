/**
 * 🔴 วรรคย้ำท้ายใบสั่งงาน — ผู้ตรวจ claude-fable-5 จับได้ 17 ส.ค. 69 (เงื่อนไขก่อน commit)
 *
 * ของเดิม: "...ห้ามขาดหาย เนื้อหาแต่ละเวอร์ชันต้องมี**ความยาวตามที่กำหนด**"
 * ปัญหา: คำว่า "ตามที่กำหนด" เคยชี้ไปที่ "ความยาวบังคับ {min}-{max} คำ" ซึ่งถอดออกไปแล้ว
 *        ⇒ กลายเป็นคำสั่งลอย ไม่มีตัวเลขให้ยึด · และอยู่ **ท้ายสุดของใบสั่งงาน**
 *          = ตำแหน่งที่โมเดลให้น้ำหนักสูงสุด ⇒ เสี่ยงให้มันย้อนไปคว้าเลขจากที่อื่น (เช่นตัวอย่างครู)
 *
 * ทางที่เลือก: **ตัดเฉพาะวรรคความยาว เก็บวรรค "ครบจำนวนเวอร์ชัน" ไว้** (ตัวนั้นกันระบบคืนงานไม่ครบ)
 *              แล้วแทนด้วยการย้ำหลักการเจ้าของสั้นๆ แทนการย้ำตัวเลข
 *
 * 🐛 ผู้ตรวจ gpt-5.6-sol จับได้ 17 ส.ค. (รุ่นแรกของผมเขียน "ครบ 3 ย่อหน้า" ตายตัว):
 *    จำนวนย่อหน้าไม่ได้เป็น 3 เสมอ — ในโหมดถอย ถ้าปิด VIRAL_HITS_FORMULA ค่า medium/long ก็อาจไม่ใช่ 3
 *    (ตอนที่จับได้ยังมีสวิตช์ข่าวบาง THIN_SOURCE_2PARA บังคับ 2 ย่อหน้าด้วย — สวิตช์นั้นถูกลบ 17 ส.ค. 69 แล้ว)
 *    ⇒ เลขตายตัวจะ **ขัดกับคำสั่งย่อหน้าในพรอมป์เดียวกัน** · ต้องอ่านจาก lenCfg เสมอ
 *
 * @param {{paraDesc?: string}} [lenCfg]
 */
export function finalReminderLengthClause(lenCfg) {
  if (isLegacyLengthOn()) return ' เนื้อหาแต่ละเวอร์ชันต้องมีความยาวตามที่กำหนด';
  const para = lenCfg?.paraDesc ? `แบ่ง ${lenCfg.paraDesc} ตามโครงสร้างข้างต้น` : 'แบ่งย่อหน้าตามโครงสร้างข้างต้น';
  return ` ทุกเวอร์ชันต้องครบข้อเท็จจริงสำคัญ ${para} และยาวพอดีกับสาระที่มีจริงในข่าว — พอดีแล้วต้องพอ ห้ามหาคำมาเติม`;
}

/**
 * ข้อความตัวอย่างในโครง JSON ของโหมด analyze
 * เดิมเป็นสวิตช์ LENGTH_BY_CONTENT: ปิด→"เนื้อหายาว {min}-{max} คำ" · เปิด→"ครบทุกประเด็นสำคัญ ไม่เกิน {max} คำ"
 * ⚠️ ตัวอย่างใน JSON สำคัญกว่าที่คิด — โมเดลมักยึดตัวอย่างมากกว่าคำอธิบายด้านบน
 */
export function analyzeJsonContentHint(lenCfg) {
  if (isLegacyLengthOn()) {
    return byContentOn()
      ? `เนื้อหาครบทุกประเด็นสำคัญ ไม่เกิน ${lenCfg.max} คำ`
      : `เนื้อหายาว ${lenCfg.min}-${lenCfg.max} คำ`;
  }
  return `เนื้อหาครบทุกประเด็นสำคัญ ยาวพอดีกับสาระที่มีจริง ไม่เกิน ${lenCfg.max} คำ`;
}
