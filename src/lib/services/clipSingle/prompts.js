export const SINGLE_REV = 'clip-single-v1-1025';

const mmss = (sec) => {
  const s = Math.max(0, Math.round(Number(sec) || 0));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
};

const PLATFORM_LABEL = { tiktok: 'TikTok', meta: 'Facebook/Instagram', youtube: 'YouTube' };

/**
 * คำสั่งดูคลิป 1 ช่วง
 * @param {object} o
 *   segment       { no, startSec, endSec } · total = จำนวนช่วงทั้งหมด
 *   timeBase      'file' = เวลานับจากต้นไฟล์ที่แนบ (ไฟล์ผ่าท่อนแล้ว) · 'clip' = นับจากต้นคลิปเต็ม
 *   wantDuration  true = ขอความยาวคลิปด้วย (ดูทั้งคลิปรอบเดียวและยังไม่รู้ความยาว)
 *   caption       ชื่อ/แคปชั่นคลิป (หลักฐานชื่อได้)
 */
export function buildWatchPrompt({ segment = null, total = 1, timeBase = 'file', wantDuration = false, caption = '' } = {}) {
  const part = total > 1 && segment
    ? `ช่วงที่ ${segment.no} จาก ${total} (นาที ${mmss(segment.startSec)}–${mmss(segment.endSec)} ของคลิปเต็ม)`
    : 'ทั้งคลิป';
  const cap = String(caption || '').trim().slice(0, 1500);
  return `คุณกำลังดูคลิปวิดีโอ ${part} เพื่อถอดเนื้อหาให้ครบ งานนี้คือ "ถอด" ไม่ใช่ "สรุป"
${cap ? `\nชื่อ/แคปชั่นของคลิป (ใช้เป็นหลักฐานชื่อคนได้):\n${cap}\n` : ''}
ส่งกลับเป็น JSON เท่านั้น ตามรูปนี้:
{
${wantDuration ? '  "durationSec": ความยาวคลิปทั้งหมดเป็นวินาที (ตัวเลข),\n' : ''}  "transcript": [ { "t": "นาที:วินาที", "speaker": "ผู้พูด", "text": "คำพูดคำต่อคำ" } ],
  "screen": [ { "t": "นาที:วินาที", "text": "ตัวหนังสือบนจอตามที่เห็น" } ],
  "visuals": [ "สิ่งที่เห็นในภาพซึ่งสำคัญต่อเรื่องแต่ไม่มีในคำพูด" ],
  "keyPoints": [ "ประเด็นสำคัญของช่วงนี้ ข้อละ 1 บรรทัด" ]
}

กติกา:
1. transcript: ถอดทุกคำพูดในช่วงนี้ตั้งแต่ต้นจนจบ คำต่อคำ เป็นภาษาไทยตามที่พูดจริง (คงคำถิ่น คำแสลง คำซ้ำ) ห้ามสรุป ห้ามข้าม ห้ามเรียบเรียงใหม่ · ช่วงที่ฟังไม่ออกเขียน "(ฟังไม่ชัด)" · เพลงประกอบไม่ต้องถอดเนื้อเพลง เขียนแค่ "(เพลงประกอบ)"
2. speaker: ใช้ชื่อเฉพาะเมื่อคลิปบอกชื่อจริง (มีคนเอ่ยชื่อในเสียง หรือขึ้นชื่อบนจอ${cap ? ' หรือมีในชื่อคลิป' : ''}) · ไม่รู้ชื่อให้ใช้บทบาทตามที่คลิปบอก เช่น "ผู้ดำเนินรายการ" "เจ้าของร้าน" "ลูกสาว" หรือ "ผู้พูด 1" "ผู้พูด 2" · ห้ามใช้สีเสื้อ การแต่งตัว หรือรูปลักษณ์แทนชื่อ · ห้ามจำหน้าแล้วเดาชื่อ ห้ามเติมนามสกุลที่คลิปไม่ได้บอก ห้ามเดาเพศ
3. t: เวลานับจาก${timeBase === 'clip' ? 'ต้นคลิปเต็ม' : 'ต้นไฟล์วิดีโอที่แนบมานี้'} (นาที:วินาที)
4. screen: คัดลอกตัวหนังสือบนจอ (ชื่อ-ตำแหน่ง ซับไตเติล ป้าย ตัวเลข) ตรงตามที่เห็น เฉพาะที่เกี่ยวกับเรื่อง ไม่ต้องใส่โลโก้ช่องหรือข้อความโฆษณา
5. visuals: เฉพาะเหตุการณ์ที่เห็นแล้วช่วยให้เข้าใจเรื่อง (ใครทำอะไร เกิดอะไรขึ้น) บรรยายตามที่เห็นจริง ห้ามตีความอารมณ์เกินภาพ
6. keyPoints: 2–8 ข้อ เรียงตามเวลา ครอบทุกเรื่องที่พูดหรือเกิดในช่วงนี้ รวมเรื่องรองด้วย
7. ห้ามใส่ความรู้นอกคลิป ห้ามเติมข้อมูลที่คลิปไม่ได้บอก
8. คลิปไม่มีคำพูดเลย ให้ transcript เป็น [] แล้วเล่าสิ่งที่เห็นใน visuals ให้ครบ`;
}

/** แปลงผลดูคลิปทุกช่วงเป็นบทถอดสำหรับคนเขียน (เวลาเป็นเวลาจริงของคลิปเต็มแล้ว) */
export function formatTranscriptForWriter(segments = []) {
  const blocks = [];
  for (const seg of segments) {
    const head = segments.length > 1 ? `[ช่วงที่ ${seg.no} · ${mmss(seg.startSec)}–${mmss(seg.endSec)}]` : '[ทั้งคลิป]';
    const lines = [head];
    if (!seg.ok) {
      lines.push('(ช่วงนี้ดูไม่สำเร็จ — ไม่มีเนื้อหา ห้ามเดาว่าช่วงนี้พูดอะไร)');
      blocks.push(lines.join('\n'));
      continue;
    }
    for (const t of seg.transcript || []) lines.push(`${t.t ? `(${t.t}) ` : ''}${t.speaker || 'ผู้พูด'}: ${t.text}`);
    if (seg.screen?.length) lines.push(`ตัวหนังสือบนจอ: ${seg.screen.map((s) => s.text).join(' · ')}`);
    if (seg.visuals?.length) lines.push(`ภาพที่เห็น: ${seg.visuals.join(' · ')}`);
    if (seg.keyPoints?.length) lines.push(`ประเด็นของช่วงนี้: ${seg.keyPoints.join(' · ')}`);
    blocks.push(lines.join('\n'));
  }
  return blocks.join('\n\n');
}

/** คำสั่งเขียนเนื้อข่าวช่องเดียว */
