/** แปลงผลดูคลิปทุกช่วงเป็นบทถอดสำหรับคนเขียน (เวลาเป็นเวลาจริงของคลิปเต็มแล้ว) */
export function formatTranscriptForWriter(segments = []) {
  const blocks = [];
  for (const seg of segments) {
    const head = segments.length > 1 ? `[ช่วงที่ ${seg.no} · ${mmss(seg.startSec)}–${mmss(seg.endSec)}]` : '[ทั้งคลิป]';
    const lines = [head];
    if (!seg.ok) {
      lines.push('(ช่วงนี้ดูไม่สำเร็จ — ไม่มีเนื้อหา ห้ามเดาว่าช่วงนี้พูดอะไร)');
      blocks.push(lines.join('\n'));
      continue;
    }
    for (const t of seg.transcript || []) lines.push(`${t.t ? `(${t.t}) ` : ''}${t.speaker || 'ผู้พูด'}: ${t.text}`);
    if (seg.screen?.length) lines.push(`ตัวหนังสือบนจอ: ${seg.screen.map((s) => s.text).join(' · ')}`);
    if (seg.visuals?.length) lines.push(`ภาพที่เห็น: ${seg.visuals.join(' · ')}`);
    if (seg.keyPoints?.length) lines.push(`ประเด็นของช่วงนี้: ${seg.keyPoints.join(' · ')}`);
    blocks.push(lines.join('\n'));
  }
  return blocks.join('\n\n');
}

