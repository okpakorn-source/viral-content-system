/**
 * ★ Clip Archive (15 ส.ค. 69) — กติกา "ไม่ให้งานพนักงานหาย" ของคลังถอดคลิป
 *
 * ที่มา (เจ้าของสั่ง 15 ส.ค.): "ต้องการเก็บทุกบทความที่พนักงานถอดเข้าคลัง"
 *   ตรวจแล้วพบว่าผลถอด "เข้าคลังครบทุกใบอยู่แล้ว" ทั้งทางเครื่องทีมและทางเว็บ — ปัญหาคือคลังลบของเก่าทิ้งเอง
 *   วัดจริง 15 ส.ค.: คลังเต็มเพดาน 400 ใบพอดี · เก่าสุด 8 ส.ค. ใหม่สุด 14 ส.ค. = เก็บได้แค่ ~6 วัน
 *
 * ไฟล์นี้เก็บเฉพาะ "ตรรกะเลือกใบที่ลบได้" ให้ทดสอบได้จริง — ตัวเขียนคลัง/สำเนาถาวรอยู่ใน route
 * (route.js ของ Next ห้าม export ชื่ออื่นนอกจาก HTTP method + config จึงแยกมาไว้ที่นี่)
 */

/** เพดานใบที่โชว์ในคลังหน้าเว็บ (ของเก่ากว่านี้ยังอยู่ในสำเนาถาวร ไม่ได้หาย) */
export const CLIP_CASE_KEEP = 400;

/**
 * เลือกใบที่ "ลบได้" ตอนคลังเกินเพดาน — เรียงเก่าสุดก่อน
 *
 * 🔴 กติกาที่ห้ามหลุดอีก: ใบที่พนักงานปักหมุด "ใช้ใบนี้" (chosen) ห้ามลบเด็ดขาด
 *    เดิมเรียงตามเวลาแล้วลบเก่าสุดล้วน → ใบปักหมุดหายเมื่ออายุเกินคลัง
 *    (การป้องกันนี้เคยมีตั้งแต่ 11 ส.ค. แล้วหลุดไปตอนย้อนยุคนิ่ง 14 ส.ค. — เทสไฟล์นี้กันไม่ให้หลุดซ้ำ)
 *
 * @param {Array<{id:string, createdAt:string, chosen?:boolean}>} all ใบทั้งหมดในคลัง
 * @param {number} keep เพดานใบที่จะเก็บไว้ในคลังหน้าเว็บ
 * @returns {Array} ใบที่ลบได้ (อาจน้อยกว่าจำนวนที่เกิน ถ้าใบเก่าเป็นใบปักหมุดหมด)
 */
export function pickCasesToPurge(all, keep = CLIP_CASE_KEEP) {
  const list = Array.isArray(all) ? all : [];
  const excess = list.length - keep;
  if (excess <= 0) return [];
  return list
    .filter(c => c && !c.chosen)
    .sort((a, b) => new Date(a.createdAt || 0) - new Date(b.createdAt || 0))
    .slice(0, excess);
}
