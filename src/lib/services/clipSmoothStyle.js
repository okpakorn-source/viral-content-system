/**
 * ★ 11 ส.ค. 69 — "แบบการเล่า" ที่พนักงานเลือกก่อนวางลิงก์ (เจ้าของสั่งวางสองระบบคู่กันให้เทสจริง)
 *
 * โมดูลนี้เล็กและบริสุทธิ์โดยตั้งใจ (ผู้ตรวจ Sol): route รับคิวต้องใช้ตัวตรวจค่านี้ได้
 * โดยไม่ต้องลากทั้ง clipInsightService (ซึ่งพ่วง client ของ AI) เข้ามาด้วย
 *
 * ค่าที่รับได้ 3 อย่าง:
 *   'a'   = จำกัดโควตาคำเล่า
 *   'c'   = แยกหลักฐานที่เห็นตรง ออกจากเรื่องที่คนเล่า
 *   'std' = สั่งใช้พรอมต์มาตรฐานเดิม "อย่างจงใจ" 🔴 ต่างจากไม่ส่งค่ามาเลย
 *           (ไม่ส่งค่า = ยอมให้ค่าตั้งต้นของระบบตัดสิน · ส่ง 'std' = ห้ามใช้ค่าตั้งต้น)
 *           บั๊กที่ปิดด้วยค่านี้: ตั้ง CLIP_SMOOTH=a ไว้ แล้วพนักงานกดปุ่ม "มาตรฐานเดิม" จะได้ A แทน
 */

/** แบบที่มีกฎของตัวเอง (ค่าที่ไปโผล่บนป้ายรุ่นพรอมต์และในคลัง)
 *  ★ 13 ส.ค. 69 (เจ้าของเคาะหลังเทียบ 2 เวอร์ชันบนคลิปเดียวกัน 2 คลิป — เลือกเพราะ "ข้อมูลดีกว่า"):
 *    "สกัดดิบ+ตัดเฟ้อ" = r2 ถอดมาตรฐานให้ครบก่อน แล้วบรรณาธิการอ่านซ้ำเกลาเฟ้อ + ด่านกลไกตัวเลขห้ามหาย
 *    เวอร์ชัน r1 (เกลาในรอบเดียว) ถูกถอดทิ้ง — เทสจริงพบฉากหาย/เปิดเรื่องด้วยพิธีกร ห้ามฟื้นโดยไม่มีคำสั่ง */
export const SMOOTH_STYLES = ['a', 'c', 'r2'];
/** ค่าสั่ง "ใช้มาตรฐานเดิม" แบบจงใจ — ไม่ใช่ชื่อแบบ จึงไม่ถูกเก็บเป็น smoothStyle ของเคส */
export const SMOOTH_STANDARD = 'std';
/** ค่าทั้งหมดที่ฝั่งหน้าเว็บส่งมาได้ (เทสใช้ตัวนี้เทียบกับรายการในหน้าเว็บ กันสองฝั่งคลาดกัน) */
export const SMOOTH_ACCEPTED = [...SMOOTH_STYLES, SMOOTH_STANDARD];

const _warned = new Set(); // เตือนค่าผิดครั้งเดียวต่อค่า (กัน log ท่วมเมื่อค่าเดิมถูกส่งซ้ำ)

/**
 * ตัวอ่านนี้ "ใจกว้างกว่า" สวิตช์ระบบโดยตั้งใจ เพราะค่ามาจากปุ่มบนหน้าเว็บ/คนกรอก
 * (สวิตช์ระบบต้องเป็น '1' เป๊ะ เพราะเปิดพลาดไม่ได้ — คนละหน้าที่กัน)
 * ค่าที่ไม่รู้จัก = คืนค่าว่าง + เตือนใน log · 🔴 ห้ามโยน error (คำขอต้องไม่ล้มเพราะค่าปุ่มเพี้ยน)
 */
function readStyle(raw, where) {
  const v = String(raw ?? '').trim().replace(/^["']+|["']+$/g, '').toLowerCase();
  if (!v) return '';
  if (SMOOTH_ACCEPTED.includes(v)) return v;
  // ตัดค่าก่อนจำ + จำกัดจำนวนที่จำ — endpoint เปิดรับค่าจากภายนอก ถ้าจำทุกค่าที่เพี้ยนจะกินแรมไม่รู้จบ
  const key = `${where}:${v.slice(0, 20)}`;
  if (!_warned.has(key)) {
    if (_warned.size >= 50) _warned.clear();
    _warned.add(key);
    console.warn(`[ClipSmooth] ⚠️ แบบการเล่าไม่รู้จัก "${v.slice(0, 20)}" (จาก ${where}) → ใช้พรอมต์มาตรฐานแทน · ค่าที่รับได้: ${SMOOTH_ACCEPTED.join(' / ')}`);
  }
  return '';
}

/**
 * ตรวจค่าที่ส่งมาอย่างเดียว ไม่แตะค่าตั้งต้นของระบบ — ใช้ตอนเก็บใบงานเข้าคิว
 * 🔴 ห้ามให้ค่าตั้งต้นของ "เครื่องที่รับคิว" ไปติดใบงานที่จะไปรันบน "อีกเครื่องหนึ่ง"
 * @returns {'a'|'c'|'std'|''}
 */
export function parseSmoothStyle(raw) {
  return readStyle(raw, 'ค่าที่ส่งมากับคำขอ');
}

/**
 * ความจริงแหล่งเดียวว่าคำขอนี้จะถอดด้วยแบบไหน — ทุกที่ต้องเรียกตัวนี้ ห้ามอ่าน env เองซ้ำ
 * ลำดับ: ค่าที่ส่งมา ('std' = จบตรงนี้ ใช้มาตรฐาน) > ค่าตั้งต้นระบบ CLIP_SMOOTH > มาตรฐาน
 * @returns {'a'|'c'|''} ค่าว่าง = พรอมต์เดิมเป๊ะ
 */
export function resolveSmoothStyle(requested) {
  const asked = parseSmoothStyle(requested);
  if (asked === SMOOTH_STANDARD) return '';        // กดมาตรฐานเดิม = ห้ามให้ค่าตั้งต้นระบบมาแทรก
  if (asked) return asked;
  // ★ 11 ส.ค. (ผู้ตรวจ Sol ข้อ 8): "ส่งค่าผิดมา" ต่างจาก "ไม่ได้ส่งอะไรมาเลย"
  //   ส่งค่าผิด = log บอกว่าจะใช้มาตรฐาน จึงต้องได้มาตรฐานจริง ห้ามแอบไปหยิบค่าตั้งต้นระบบมาใช้แทน
  //   (ไม่งั้นพนักงานส่งค่าพิมพ์ผิด แล้วได้แบบ A โดยไม่มีใครรู้ ทั้งที่ log เขียนว่าใช้มาตรฐาน)
  const sentSomething = String(requested ?? '').trim() !== '';
  if (sentSomething) return '';
  const fallback = readStyle(process.env.CLIP_SMOOTH, 'CLIP_SMOOTH');
  return fallback === SMOOTH_STANDARD ? '' : fallback;
}
