/**
 * 🎬 clipBrain/promoTopics.js — หัวข้อ "โปรโมตของรายการ" ไม่ใช่เนื้อข่าว (P13 · 14 ก.ย. 69 เจ้าของสั่ง)
 * ------------------------------------------------------------------
 * แยก 2 ระดับ (พิสูจน์กับหัวข้อจริง 4,759 แถวจากคลัง 889 เคส — ตัวกรองแบบคำเดียวจับเนื้อข่าวผิด เช่น
 * "ประสบการณ์เล่นโฆษณา" "ช่องทางบริจาค…และปิดรายการ" "นนท์มอบของขวัญ…และปิดรายการ"):
 *   'external' = โปรโมตเนื้อหาอื่น/นอกคลิป: ตัวอย่างช่วงต่อไป/ตอนหน้า · โฆษณา/สปอต/ช่วงคั่น · คำชวนติดตาม/ฝากผลงาน/ประชาสัมพันธ์ช่องทาง
 *                → ตัดออกจากหลักฐานที่ส่งให้แต่งเรื่อง + พรอมต์ "ห้ามเขียนถึง" + ไม่นับว่าหาย
 *   'internal' = โครงรายการล้วนๆ ของคลิปนี้: เปิดรายการ/ปิดรายการ/ปิดท้าย/ไฮไลท์เปิด/ไตเติล ที่ไม่มีเนื้อหาอื่นปน
 *                → แค่ไม่นับว่าหาย (หลักฐานคงเดิม) เพราะ AI-summary แถวนี้ไม่มีเนื้อ
 *   null       = เนื้อหา (รวมแถวผสม เช่น "สมจิตรมอบดอกไม้…ปิดท้ายรายการ") → พฤติกรรมเดิมทุกประการ
 *
 * หลักตัดสิน "ล้วนๆ": ตัดวลีโปรโมต/โครง + คำเชื่อม + คำบอกบทบาท/แพลตฟอร์ม (ผู้ประกาศ เพจ ช่อง ยูทูบ…) + อักษรละติน/ตัวเลข
 * แล้วดูว่า "เนื้อที่เหลือ" มีตัวอักษรไทย < 6 หรือไม่ · วลีที่ชี้เนื้อหาอื่น (ตัวอย่างช่วงต่อไป / คำชวนติดตาม / โฆษณา)
 * ดูเฉพาะ "ส่วนหน้าวลี": ถ้าหน้าวลีไม่มีเนื้อ = โปรโมต (เนื้อหลังวลีคือชื่อเพจ/ตอนหน้า ไม่ใช่ข่าว)
 *
 * env: CLIP_PROMO_TOPIC_FILTER='0' ปิดทั้งหมด · CLIP_PROMO_TOPIC_EXTRA='คำ1|คำ2' คำตรงตัวที่ถือเป็นโปรโมตนอกคลิป (external)
 */

// ตัวอย่างเนื้อหาอื่น — แข็ง: ตัดสินจากตำแหน่ง (นำหน้า หรือหน้าวลีไม่มีเนื้อ = โปรโมต; เนื้อหานำ = เนื้อหา)
const TEASER_PATTERNS = Object.freeze([
  /ตัวอย่าง(?:\s*(?:ช่วง|รายการ|ไฮไล[ทต]์?|ตอน|เนื้อหา|อีพี|สิ่งที่จะได้ชม)){1,3}\s*(?:ใน)?\s*(?:ช่วง)?\s*(?:ต่อไป|ถัดไป|หน้า)/u,
  /ช่วง(?:ต่อไป|ถัดไป)ของรายการ/u, /พรีวิว(?:ช่วง|ตอน)?\s*(?:ต่อไป|ถัดไป)/u,
  /แขกรับเชิญ(?:ใน)?ช่วง(?:ถัดไป|ต่อไป)|ช่วง(?:ถัดไป|ต่อไป)(?:เกี่ยวกับ|พบกับ)/u,
]);
// อ่อน (วงตรวจ 14 ก.ย.): คำที่ข่าวธรรมดาใช้ได้ ("จะขึ้นราคาสัปดาห์หน้า") — เป็นโปรโมตเฉพาะเมื่อทั้งแถวมีแต่โครง
const TEASER_WEAK_PATTERNS = Object.freeze([
  /ตอนต่อไป|ตอนหน้า|สัปดาห์หน้า|คราวหน้า|อีพีหน้า|ep\.?\s*หน้า/u,
  /(?:พบกัน|เจอกัน)(?:ใหม่)?(?:ใน)?(?:ตอน|สัปดาห์|ครั้ง|คราว)หน้า/u,
]);
// โฆษณา / สปอต / ช่วงคั่น / คำชวนติดตาม / ฝากผลงาน — ตัดสินจากตำแหน่งเหมือน teaser (ส่วนหลังวลีมักเป็นชื่อสินค้า/เพจ/ช่อง)
const AD_PATTERNS = Object.freeze([
  /ช่วง\s*(?:เบรก|คั่น)?\s*(?:โฆษณา|โปรโม[ตท]|สปอนเซอร์|ประชาสัมพันธ์|แนะนำ(?:ผลิตภัณฑ์|สินค้า)(?:ผู้สนับสนุน)?)/u,
  /(?:เบรก|สปอต)\s*(?:โฆษณา|ประชาสัมพันธ์)?|^โฆษณา|ช่วงคั่น(?:รายการ)?|ตัดเข้าเบรก/u,
  /ผู้สนับสนุนรายการ|แนะนำสปอนเซอร์|โปรโมชั่น|โปรโมชัน|ประชาสัมพันธ์/u,
  /ประชาสัมพันธ์(?:ช่องทาง|กิจกรรม|งาน|ซีรีส์|ละคร|ภาพยนตร์|รายการ)/u,
  /ติดตามชม|ฝาก(?:กด)?ติดตาม|เชิญชวน(?:กด)?ติดตาม|ชวน(?:กด)?ติดตาม(?:ช่อง|เพจ|รายการ)|ฝากช่องทาง|แจ้งช่องทาง|บอกช่องทาง|ช่องทาง(?:การ)?ติดตาม|กดติดตาม|กดไล[กค]์|กด\s*like|กดแชร์|กด\s*share|กดกระดิ่ง|subscribe|ห้ามพลาด|อย่าลืม(?:กด)?ติดตาม|ฝากผลงาน|ฝากช่อง|ฝากเพจ/u,
]);
// โครงรายการ — ไม่มีเนื้อในตัวเอง
const STRUCTURE_PATTERNS = Object.freeze([
  /(?:เปิด|ปิด)รายการ|ปิดท้าย(?:คลิป|รายการ)?|ช่วงท้าย(?:คลิป|รายการ)?|ท้ายคลิป|ส่งท้าย(?:รายการ)?|กล่าวปิด|ปิดช่วง/u,
  /ไฮไล[ทต]์?(?:\s*(?:และ)?\s*(?:เปิดรายการ|ประจำ(?:ตอน|สัปดาห์|อีพี|วัน)?|รายการ|ของรายการ))?/u,
  /ตัวอย่าง(?:\s*(?:ช่วง|รายการ|ไฮไล[ทต]์?|เนื้อหา))+/u, /ไตเติล|อินโทร|เพลงประจำรายการ|แนะนำช่วง(?:ต่างๆ|ต่าง ๆ|ในรายการ)|พบกันใหม่/u,
  /(?:แนะนำ|ต้อนรับ|เปิดตัว)\s*แขกรับเชิญ|ต้อนรับ|แนะนำ(?:เนื้อหา|ตัว|พิธีกร)?|ทักทาย(?:ผู้ชม|พิธีกร)?/u,
  /บทสรุป|สรุป(?:รายการ|ข้อคิด|บทเรียน)?|เกริ่น(?:นำ)?|ขอบคุณ(?:ผู้สนับสนุน|ผู้ชม|แฟนคลับ)?/u,
]);
// คำเชื่อม/คำบอกบทบาท/แพลตฟอร์ม ที่ไม่นับเป็นเนื้อ เวลาวัดว่า "ที่เหลือ" มีเนื้อหาไหม
const FILLER_RE = /และ|พร้อม(?:กับ|ทั้ง)?|ก่อน|หลังจาก|ประจำ|สัปดาห์|ตอน|ช่วง|รายการ|ของ|กล่าว|แจ้ง|บอก|ฝาก|พูดคุย|คุยกัน|ต่างๆ|ต่าง ๆ|เนื้อหา|กับ|ใน|ที่|นี้|วันนี้|อีพี|ทาง|โดย|ผลงาน|ปัจจุบัน|พิเศษ|ผู้ประกาศ(?:ข่าว)?|ผู้ดำเนินรายการ|พิธีกร|ทีมงาน|ผู้ชม|ผู้ติดตาม|แฟนคลับ|แฟนๆ|คลิป|เพจ|ช่อง|ยูทูบ|เฟซบุ๊ก|ติ๊กต็อก|ไอจี|ทีวี|เอชดี|ออนไลน์|ข่าวสด|ข่าวสาร|เว็บไซต์|แอป|โซเชียล|ทุกช่องทาง|ค่าย|มิวสิค|สินค้า|ผลิตภัณฑ์|กิจกรรม|งาน|ซีรีส์|ละคร|ภาพยนตร์|สมาชิก|เข้าสู่|ส่ง/gu;

// ★ วงตรวจ: ตัดอักขระความกว้างศูนย์ (U+200B–D, FEFF) ก่อน — ไม่งั้น "ตัวอย่าง\u200Bช่วงต่อไป" หลุด
const normalize = (v) => String(v == null ? '' : v).replace(/[\u200B-\u200D\uFEFF]/g, '').toLowerCase().replace(/\s+/g, ' ').trim();
const thaiChars = (s) => (String(s).match(/[ก-๙]/gu) || []).length;
const filterOff = () => String(process.env.CLIP_PROMO_TOPIC_FILTER ?? '').trim() === '0';
const ALL_PHRASES = [...TEASER_PATTERNS, ...TEASER_WEAK_PATTERNS, ...AD_PATTERNS, ...STRUCTURE_PATTERNS];

/** ข้อความหัวข้อจากแถว timeline ทุกรูปทรงที่ระบบใช้ ({topic} / {title} / {text} / string) */
export function promoTopicText(row) {
  if (row == null) return '';
  if (typeof row === 'string') return row;
  if (typeof row !== 'object') return String(row);
  for (const key of ['topic', 'title', 'text', 'point', 'detail']) {
    if (typeof row[key] === 'string' && row[key].trim()) return row[key];
  }
  return '';
}

/** เนื้อที่เหลือหลังตัดวลีโปรโมต/โครงรายการ/คำเชื่อม/บทบาท/อักษรละติน-ตัวเลข (ชื่อรายการภาษาอังกฤษ ชื่อสินค้า) */
function residueOf(s) {
  let r = s;
  for (const re of ALL_PHRASES) r = r.replace(new RegExp(re.source, 'gu'), ' ');
  r = r.replace(/[a-z0-9]+/giu, ' ').replace(FILLER_RE, ' ').replace(/[^ก-๙]+/gu, ' ');
  return r.replace(/\s+/g, ' ').trim();
}
const residueChars = (s) => thaiChars(residueOf(s));
/** ตำแหน่งแรกที่วลีชุดนี้ปรากฏ (-1 = ไม่มี) */
function firstIndex(patterns, s) {
  const found = patterns.map((re) => s.search(re)).filter((i) => i >= 0);
  return found.length ? Math.min(...found) : -1;
}
/** วลีชี้เนื้อหาอื่นถือเป็นโปรโมตเมื่อ "หน้าวลี" ไม่มีเนื้อ (เนื้อหลังวลี = ชื่อเพจ/สินค้า/ตอนหน้า) */
const leadsRow = (s, idx) => idx <= 2 || residueChars(s.slice(0, idx)) < 6;

/**
 * @returns {'external'|'internal'|null}
 *   external = โปรโมตเนื้อหาอื่น (ตัดออก+ห้ามเขียน) · internal = โครงรายการล้วน (แค่ไม่นับว่าหาย) · null = เนื้อหา
 */
export function promoTopicClass(topicOrRow) {
  if (filterOff()) return null;
  const s = normalize(typeof topicOrRow === 'object' ? promoTopicText(topicOrRow) : topicOrRow);
  if (!s) return null;
  const teaserAt = firstIndex(TEASER_PATTERNS, s);
  if (teaserAt >= 0) return leadsRow(s, teaserAt) || residueChars(s) < 6 ? 'external' : null;
  const extra = String(process.env.CLIP_PROMO_TOPIC_EXTRA || '').split('|').map(normalize).filter(Boolean);
  if (extra.some((word) => s.includes(word))) return 'external';
  const adAt = firstIndex(AD_PATTERNS, s);
  // โฆษณา/ชวนติดตาม: ต้องทั้งหน้าวลีไม่มีเนื้อ และทั้งแถวเหลือเนื้อ < 10 (ยอมให้ชื่อสินค้า/เพจสั้นๆ) — แถวผสมเนื้อหา เช่น "ฟ้า ฝากช่องทางการขายของ…ก่อนปั่นจักรยานกลับบ้าน" = เนื้อหา
  if (adAt >= 0 && leadsRow(s, adAt) && residueChars(s) < 10) return 'external';
  if (TEASER_WEAK_PATTERNS.some((re) => re.test(s)) && residueChars(s) < 6) return 'external';
  if (STRUCTURE_PATTERNS.some((re) => re.test(s)) && residueChars(s) < 6) return 'internal';
  return null; // มีเนื้อหาจริงปนอยู่ (หรือไม่มีวลีโปรโมตเลย) = เนื้อหา
}

/** จริงเมื่อเป็นโปรโมตเนื้อหาอื่น/โฆษณา/คำชวนติดตาม — ใช้ตัดออกจากหลักฐานและบอกผู้แต่ง "ห้ามเขียนถึง" */
export function isPromoTopic(topicOrRow) { return promoTopicClass(topicOrRow) === 'external'; }
/** จริงเมื่อไม่ใช่เนื้อหา (โปรโมตหรือโครงรายการล้วน) — ใช้กับด่าน "ของหาย-ประเด็น" */
export function isNonContentTopic(topicOrRow) { return promoTopicClass(topicOrRow) !== null; }

/** จำกัดขนาดรายการที่ตัด (อยู่ใน clipMeta ซึ่งไม่ผ่านตัวตัดงบหลักฐาน — วงตรวจ 14 ก.ย.): สูงสุด 12 แถว · เวลา ≤ 24 · หัวข้อ ≤ 80 ตัวอักษร */
export const PROMO_SKIPPED_MAX = 12;
export function capPromoSkipped(items) {
  return (Array.isArray(items) ? items : []).slice(0, PROMO_SKIPPED_MAX)
    .map((p) => ({ time: String(p?.time ?? '').trim().slice(0, 24), topic: String(p?.topic ?? '').trim().slice(0, 80) }));
}

export const PROMO_TOPIC_PATTERNS = Object.freeze({ teaser: TEASER_PATTERNS, teaserWeak: TEASER_WEAK_PATTERNS, ad: AD_PATTERNS, structure: STRUCTURE_PATTERNS });
