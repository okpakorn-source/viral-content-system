/** แทนวลีเสี่ยงในข้อความเดียว */
export function sanitizeClipString(input) {
  if (typeof input !== 'string' || !input) return input;
  if (process.env.CLIP_SAFE_TEXT === '0') return input;
  let out = input;
  for (const [re, rep] of PHRASE_REPLACEMENTS) out = out.replace(re, rep);
  return out;
}

// คีย์อันตราย — ถ้า copy ด้วย out[k]=... ตรงๆ จะเปลี่ยน prototype ของ out (out เป็น {} ธรรมดา
// ที่สืบทอด Object.prototype ซึ่งมี __proto__ เป็น accessor) ข้ามทิ้งเสมอตอน traverse
const UNSAFE_TRAVERSE_KEYS = new Set(['__proto__', 'constructor', 'prototype']);

// เพดานความลึก recursion กันสแต็กล้นจากโครงสร้างซ้อนลึกผิดปกติ (เกินเพดาน = คืนดิบ ห้าม throw)
const MAX_SANITIZE_DEPTH = 32;

function sanitizeClipTextDeep(value, depth, seen) {
  if (depth > MAX_SANITIZE_DEPTH) return value; // เกินเพดาน → ไม่แตะ คืนค่าดิบ
  if (typeof value === 'string') return sanitizeClipString(value);
  if (Array.isArray(value)) {
    if (seen.has(value)) return value; // เจอ cycle (อ้างตัวเองทางอ้อม) → คืนดิบ ไม่ไล่ซ้ำ
    seen.add(value);
    const out = value.map((item) => sanitizeClipTextDeep(item, depth + 1, seen));
    seen.delete(value); // ออกจากกิ่งนี้แล้ว คืนสิทธิ์ให้กิ่งอื่นที่ reference ของเดิม (ไม่ใช่ cycle จริง)
    return out;
  }
  if (value && typeof value === 'object') {
    if (seen.has(value)) return value;
    seen.add(value);
    const out = {};
    for (const k of Object.keys(value)) {
      if (UNSAFE_TRAVERSE_KEYS.has(k)) continue;
      out[k] = sanitizeClipTextDeep(value[k], depth + 1, seen);
    }
    seen.delete(value);
    return out;
  }
  return value;
}

/** แทนวลีเสี่ยงทุกช่องในผลลัพธ์ (object/array ซ้อนกี่ชั้นก็ได้ ไม่เกิน 32 ชั้น + กัน cycle/prototype pollution) */
export function sanitizeClipText(value) {
  if (process.env.CLIP_SAFE_TEXT === '0') return value;
  return sanitizeClipTextDeep(value, 0, new WeakSet());
}

/**
 * ตรวจว่าข้อความมีร่องรอย "ถูกตัวกรองกลางทำเพี้ยน" หรือไม่ (ของที่ผ่านเส้นทางเดิมมาก่อน)
 * ใช้ติดธงเตือนบนใบเก่า — ไม่ได้ซ่อมให้ เพราะซ่อมแล้วอาจเดาคำผิด
 */
const CORRUPTION_SIGNS = [
  /[ก-ฮ]ร่างผู้เสียชีวิต[ก-ฮิีุู็่้๊๋ัํ]/,
  /ทำให้เสียชีวิต(เชื้อ|แมลง|หญ้า|ตัดวงจร)/,
  /บรรยากา ?ร่างผู้เสียชีวิต|ประกา ?ร่างผู้เสียชีวิต/,
];
export function detectFilterCorruption(text) {
  const s = typeof text === 'string' ? text : JSON.stringify(text || '');
  for (const re of CORRUPTION_SIGNS) { const m = s.match(re); if (m) return { corrupted: true, sample: m[0] }; }
  return { corrupted: false, sample: null };
}
