// ★ 25 ต.ค. 69 ด่านเดาเพศชั้นสุดท้าย — นักเขียนยังใส่ "เธอ" เองบางเวอร์ชัน (2/10) ทั้งที่ต้นฉบับไม่บอกเพศ
//   (ข่าวพยาบาลร้อยเอ็ด: "พว.กนกวรรณ" ไม่มีคำบอกเพศ แต่ข่าวเขียน "เธอไม่รอช้า") · แก้ต้นทางแล้ว (กฎห้ามเดาเพศขั้นแตกประเด็น/วางโครง)
//   รอบ 2 (ผู้ตรวจรอบ 2 FAIL — แทนทุกกรณีเปลี่ยนความหมายได้: "เธอ" ที่หมายถึงคุณยายกลายเป็นพยาบาล) → แทนเฉพาะต้นฉบับไม่มีผู้หญิง
//   รอบ 3 (ผู้ตรวจรอบ 3 FAIL — เรื่องมีหลายคน "เจ้าตัว" ชี้ผิดคน (เคสเมล บี/เนเน่) + regex คำบอกผู้หญิงตกหลายคำ) →
//   ★ เจ้าของเลือก "เตือนอย่างเดียว ไม่แก้เนื้อ": ด่านนี้ไม่แตะเนื้อข่าวแล้ว — ติดป้าย _genderWarning ให้บอทโชว์ให้พนักงานเช็ค
//     ① ต้นฉบับใช้ "เธอ/หล่อน" เอง → ไม่เตือน (นักเขียนใช้ตามต้นฉบับ)
//     ② ต้นฉบับมีคำบอกผู้หญิง → ข่าวที่มี "เธอ" ติดป้าย "เช็คว่าหมายถึงใคร"
//     ③ ต้นฉบับไม่มีคำบอกผู้หญิงเลย → ข่าวที่มี "เธอ" ติดป้าย "น่าจะเดาเพศ"
//   ถอย: GENDER_NEUTRAL_FIX=0/off/false/no = ไม่เตือน

// รอบ 4 (ผู้ตรวจรอบ 4): กันแบบเดียวกับฝั่งเนื้อข่าว — "พวกเธอ" "มาเธอร์แคร์" "บราเธอร์" ราชทินนาม "พระเจ้าลูกเธอ" ไม่ใช่การเรียกคนด้วย "เธอ"
const RAW_PRONOUN = /(?<!พวก|เจ้าลูก)เธอ(?!ร์)|หล่อน/u;
// มีผู้หญิงในต้นฉบับ (บอกเพศตรง + คำนำหน้า/เครือญาติ/บทบาทหญิง + คำพูดลงท้ายผู้หญิง) — ใช้เลือกข้อความเตือน ② หรือ ③
//   รอบ 3: แม่ กันเฉพาะคำที่ไม่ใช่คน (แม่น้ำ/แม่นยำ/"แม่น" ท้ายคำ/แม่ทัพ…) — "แม่น้อง…" "แม่นาง" "แม่บ้าน" นับ ·
//   นาง กันแค่ ขุนนาง/บุนนาง (เดิมกันทุกตัวอักษรไทยข้างหน้า → "โดยนางสมศรี" หลุด) · เพิ่ม พญ./ทพญ./ภญ./สพญ./อาม่า/เจ๊/ซิ้ม/สะใภ้/ภิกษุณี
const RAW_FEMALE_PERSON = new RegExp([
  'นางสาว', 'น\\.ส\\.', 'เด็กหญิง', 'ด\\.ญ\\.', 'หญิง', 'สาว(?!ก(?:ของ|ทั้ง|ผู้|[^\\u0E00-\\u0E7F]|$))', '(?<!ขุน|บุน)นาง(?=[\\s\\u0E00-\\u0E7F])', 'พระนาง', 'คุณนาย',
  'พญ\\.', 'ทพญ\\.', 'ภญ\\.', 'สพญ\\.', 'อาม่า', 'เจ๊', 'ซิ้ม', 'สะใภ้', 'ภิกษุณี',
  // รอบ 4 (ผู้ตรวจรอบ 4): ขยาย/ป้าย/ย่าน/อย่า/แม่สอด/แม่นมาก ไม่ใช่คำบอกผู้หญิง
  '(?<!ข)ยาย', '(?<!อ)ย่า(?!ง|น)', 'ป้า(?!ย)', 'คุณแม่', 'มารดา',
  'แม่(?!น้ำ|นยำ|นมาก|น(?![\\u0E00-\\u0E7F])|ทัพ|เหล็ก|แบบ|ไม้|กุญแจ|ข่าย|สอด|สาย|ริม|แตง|ฮ่องสอน|จัน|แจ่ม|เมาะ|ระมาด|โขง|ปิง|กลอง|ยม|ลาว|วาง|ออน|พริก|สรวย|สะเรียง|ฟ้าหลวง)', 'ภรรยา', 'ภริยา',
  'ค่ะ', 'คะ(?![ก-๙])', 'ดิฉัน', 'ราชินี',
].join('|'), 'u');
const PRONOUN_IN_TEXT = /(?<!พวก)เธอ(?!ร์)/u;

export function isGenderNeutralFixEnabled() {
  const raw = String(process.env.GENDER_NEUTRAL_FIX ?? '').trim().replace(/^["']+|["']+$/g, '').trim().toLowerCase();
  return !['0', 'off', 'false', 'no'].includes(raw);
}

/** ต้นฉบับอยู่กรณีไหน: 'pronoun' (①) · 'female' (②) · 'none' (③) */
export function rawGenderCase(rawText) {
  const raw = String(rawText || '');
  if (RAW_PRONOUN.test(raw)) return 'pronoun';
  if (RAW_FEMALE_PERSON.test(raw)) return 'female';
  return 'none';
}

export const GENDER_WARNING_TEXT = 'ใช้คำว่า "เธอ" แต่ต้นฉบับไม่ได้ใช้คำนี้ — เช็คว่า "เธอ" หมายถึงใคร และคนนั้นเป็นผู้หญิงตามต้นฉบับจริง';
export const GENDER_GUESS_WARNING_TEXT = 'ใช้คำว่า "เธอ" แต่ต้นฉบับไม่บอกเพศใครเลย — น่าจะเดาเพศจากชื่อ ให้เช็คแล้วแก้เป็นชื่อ ตำแหน่ง หรือ "เจ้าตัว"';

/** คืน { versions (อาเรย์ใหม่ · ฉบับที่ไม่ติดป้าย = ตัวเดิม · เนื้อข่าวไม่ถูกแก้), changed: [] (คงรูปเดิมให้ผู้เรียก), warned: [version], case } */
export function neutralizeGuessedGender(versions, rawText) {
  if (!Array.isArray(versions)) return { versions, changed: [], warned: [], case: null };
  if (!isGenderNeutralFixEnabled() || !rawText) return { versions, changed: [], warned: [], case: null };
  const kase = rawGenderCase(rawText);
  if (kase === 'pronoun') return { versions, changed: [], warned: [], case: kase };
  const warning = kase === 'female' ? GENDER_WARNING_TEXT : GENDER_GUESS_WARNING_TEXT;
  const warned = [];
  const out = versions.map((v, i) => {
    if (!v || typeof v !== 'object' || typeof v.content !== 'string') return v;
    if (!PRONOUN_IN_TEXT.test(v.content)) return v;
    warned.push(i + 1);
    return { ...v, _genderWarning: warning };
  });
  return { versions: out, changed: [], warned, case: kase };
}
