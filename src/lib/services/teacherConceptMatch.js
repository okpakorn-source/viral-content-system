const FACET_W = Object.freeze({ event: 3, who: 2, feel: 0.6 });
// เส้นขั้นต่ำ: ต้องตรงกันอย่างน้อย 1 เหตุการณ์ หรือ 2 ความหมาย และคะแนนถึงเกณฑ์ — ไม่ถึง = ไม่มีครูที่ตรงพอ → ผู้เรียกถอยวิธีเดิม
export const MATCH_FLOOR = 1.2;

const TEACHER_HEAD = 300;
const NEWS_BODY = 2000;

/** แปลงข้อความเป็นชุดความหมาย { id: นับครั้ง } — hasWord = ตัวอ่านคำของตัวคัดโผเดิม (ขอบคำไทยแบบเบาๆ) */
export function conceptsIn(text, hasWord) {
  const hay = String(text || '').toLowerCase();
  const out = {};
  if (!hay) return out;
  for (const c of CONCEPTS) {
    let n = 0;
    for (const t of c.terms) if (hasWord(hay, t.toLowerCase())) n += 1;
    if (n) out[c.id] = n;
  }
  return out;
}

const _byId = Object.fromEntries(CONCEPTS.map((c) => [c.id, c]));

/** ชุดความหมายของครู 1 ใบ: บัตรลักษณะ (เชื่อเต็ม) + หัวเรื่อง (เสริม 0.5) — ไม่อ่านเนื้อโพสต์: วัดแล้วดึงคำรบกวนจนครูที่ตรงจริงถูกหักคะแนน */
function teacherProfile(row, ess, hasWord) {
  const e = ess || {};
  const card = [...(e.themes || []), ...(e.emotion || []), e.tone || '', e.structure || ''].join(' ');
  const fromCard = conceptsIn(card, hasWord);
  const fromTitle = conceptsIn(String(row?.title || '').slice(0, TEACHER_HEAD), hasWord);
  const prof = {};
  for (const id of new Set([...Object.keys(fromCard), ...Object.keys(fromTitle)])) prof[id] = fromCard[id] ? 1 : 0.5;
  return prof;
}

/** ชุดความหมายของข่าว: แต่ละช่องให้น้ำหนักต่างกัน รวมแล้วเพดาน 3 ต่อความหมาย */
export function newsProfile(brief, hasWord) {
  const b = brief && typeof brief === 'object' ? brief : {};
  const parts = [
    [b.title, 1.5], [b.coreStory, 1.2], [b.cardEssence, 1.0], [String(b.excerpt || '').slice(0, NEWS_BODY), 1.0],
  ];
  const prof = {};
  for (const [text, w] of parts) {
    const cs = conceptsIn(text, hasWord);
    for (const id in cs) prof[id] = Math.min(3, (prof[id] || 0) + w * (cs[id] > 1 ? 1.5 : 1)); // หลายคำในความหมายเดียว = ชัดขึ้น แต่ไม่เกิน 1.5 เท่า
  }
  return prof;
}

let _cache = null;
function _teacherIndex(rows, essences, hasWord) {
  if (_cache && _cache.rows === rows && _cache.ess === essences) return _cache;
  const profiles = rows.map((r) => teacherProfile(r, essences?.[r.id], hasWord));
  const N = profiles.length || 1;
  const df = {};
  for (const p of profiles) for (const id in p) df[id] = (df[id] || 0) + 1;
  const idf = {};
  for (const c of CONCEPTS) idf[c.id] = Math.log((N + 1) / ((df[c.id] || 0) + 1)) + 0.1;
  const mass = profiles.map((p) => Math.sqrt(Object.keys(p).reduce((s, id) => s + idf[id] * FACET_W[_byId[id].facet] * p[id], 0)) || 1);
  _cache = { rows, ess: essences, profiles, idf, mass };
  return _cache;
}

/**
 * จับคู่ครู 2 ใบกับข่าว — นิ่ง 100% · คืน { list: [row, row?], reason, fell, scored? }
 * list ว่าง = ไม่มีครูที่ตรงพอ (fell=true) → ผู้เรียกถอยวิธีเดิม
 */
export function matchTeachers(brief, rows, essences, hasWord) {
  if (!Array.isArray(rows) || rows.length === 0) return { list: [], fell: true, reason: 'ไม่มีแถวจากคลัง' };
  if (!essences || !Object.keys(essences).length) return { list: [], fell: true, reason: 'บัตรลักษณะว่าง' };
  const news = newsProfile(brief, hasWord);
  if (!Object.keys(news).length) return { list: [], fell: true, reason: 'อ่านความหมายจากข่าวไม่ได้เลย' };
  const idx = _teacherIndex(rows, essences, hasWord);
  const scored = rows.map((r, i) => {
    const p = idx.profiles[i];
    let s = 0; const hits = [];
    for (const id in news) {
      if (!p[id]) continue;
      const w = idx.idf[id] * FACET_W[_byId[id].facet] * news[id] * p[id];
      s += w; hits.push(id);
    }
    return { r, score: s / idx.mass[i], hits, events: hits.filter((id) => _byId[id].facet === 'event') };
  }).sort((a, b) => b.score - a.score || (String(a.r.id) < String(b.r.id) ? -1 : 1)); // ห้าม localeCompare (ICU ต่างเครื่อง — บทเรียน 16 ส.ค.)
  const top = scored[0];
  if (!top || top.score < MATCH_FLOOR || (top.events.length === 0 && top.hits.length < 2)) {
    return { list: [], fell: true, reason: `ไม่มีครูที่ตรงพอ (สูงสุด ${top ? top.score.toFixed(2) : 0} < ${MATCH_FLOOR})` };
  }
  // ใบที่ 2 = อันดับถัดไปที่ไม่ใช่โพสต์เดียวกัน (คลังมีครูซ้ำ 2 id ชื่อเดียวกัน) — วัดแล้ว: บังคับ "คนละเหตุการณ์" ทำให้ครูที่ตรงอันดับ 2 หลุด
  //   (ข่าวพยาบาล: "ไม่ได้อยู่ในหน้าที่ เป็นแค่พลเมืองขับรถผ่าน" ถูกแทนด้วยครูเจาะน้ำ) · ความหลากหลายข้ามข่าววัดแยกที่คลังงานจริง
  const titleOf = (x) => String(x.r.title || '').trim().slice(0, 60);
  const second = scored.slice(1).find((x) => x.score > 0 && x.r.id !== top.r.id && titleOf(x) !== titleOf(top)) || null;
  const list = second && second.score >= MATCH_FLOOR * 0.5 ? [top, second] : [top];
  const why = (x) => `[${x.r.category}] ${String(x.r.id).slice(0, 8)} ${x.score.toFixed(2)} ${x.hits.join(',')}`;
  return { list: list.map((x) => x.r), fell: false, reason: list.map(why).join(' | '), scored: scored.slice(0, 8).map((x) => ({ id: x.r.id, score: +x.score.toFixed(3), hits: x.hits })) };
}
