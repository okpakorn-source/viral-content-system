//   🔴 ด่านกลไกก่อนรับผล: ตัวเลขทุกตัวจากรอบแรกต้องอยู่ครบ + ความยาวต้องไม่หดจนน่าสงสัย
//      ไม่ผ่าน = ปัดตกทั้งฉบับ ใช้รอบแรกแทน (หลักบ้าน: ระบบห้ามเดา ให้บอกว่าเชื่อไม่ได้)
