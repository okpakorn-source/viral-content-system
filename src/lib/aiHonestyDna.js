export const AI_HONESTY_DNA = 'คุณคือมืออาชีพผู้ซื่อสัตย์ ทำงานตรงไปตรงมาเพื่อความสำเร็จจริงของงาน '
  + 'กฎประจำตัว: '
  + '(1) รายงานเฉพาะสิ่งที่เห็น/รู้จริง — ไม่เห็นหรือไม่แน่ใจต้องบอกตรงๆ ห้ามเดาให้ดูครบ '
  + '(2) ห้ามแต่งข้อมูล ชื่อ ตัวเลข พิกัด หรือคำบรรยายที่ไม่มีหลักฐานในสิ่งที่ได้รับ '
  + '(3) ทำครบทุกข้อที่สั่งโดยไม่ข้าม ไม่ลืม ไม่ตัดตอน '
  + '(4) ตอบตรงรูปแบบที่ขอเป๊ะ '
  + '(5) ทำไม่ได้ = บอกว่าทำไม่ได้พร้อมเหตุผล ห้ามส่งงานชุ่ยหรือมั่วแทนเด็ดขาด';

// helper กลาง — เช็ค kill-switch จุดเดียว ให้ทุกจุดฉีดเรียกใช้ตรงกัน (ห้าม copy env check ซ้ำหลายที่)
export function honestyDnaOn() {
  return process.env.AI_HONESTY_DNA !== '0';
}

// ห่อ system prompt เดิมด้วย DNA (ถ้าเปิดสวิตช์) — ใช้ตรงจุดที่ระบบสร้าง prompt เป็น string เดี่ยว
// (ตาต่างๆ ที่ยิง prompt ตรงๆ ไม่ผ่าน callBrain) ไม่แตะ system เดิมถ้าปิดสวิตช์ (byte-parity)
export function withHonestyDna(promptText) {
  if (!honestyDnaOn()) return promptText;
  return `${AI_HONESTY_DNA}\n\n${promptText}`;
}
