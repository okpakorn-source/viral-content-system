const ON_TOKENS = ['1', 'on', 'true', 'yes'];

/** @returns {boolean} true = ให้ท่อข่าวออกไปค้นข้อมูลเสริมได้ · false (ค่าตั้งต้น) = ห้ามค้น */
export function isNewsResearchOn() {
  const raw = String(process.env.NEWS_RESEARCH ?? '')
    .trim().replace(/^["']+|["']+$/g, '').trim().toLowerCase();
  return ON_TOKENS.includes(raw);
}

